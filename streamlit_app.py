"""Interactive dashboard for the fraud and drift experiment."""

import json
import subprocess
import sys
import tempfile
from pathlib import Path

import pandas as pd
import streamlit as st

from src.config import DATA_PATH, RESULTS_DIR


PROJECT_ROOT = Path(__file__).resolve().parent

st.set_page_config(
    page_title="Fraud & Drift Monitor",
    page_icon="🛡️",
    layout="wide",
    initial_sidebar_state="expanded",
)


def show_results():
    """Load and display outputs produced by the most recent pipeline run."""
    metrics_file = RESULTS_DIR / "metrics.csv"
    drift_file = RESULTS_DIR / "drift_report.json"
    if not metrics_file.exists() or not drift_file.exists():
        st.info("Run an experiment to see metrics, drift status, and cost estimates here.")
        return

    metrics = pd.read_csv(metrics_file)
    drift = json.loads(drift_file.read_text())
    observed = drift["observed_later_window"]
    later_metrics = metrics[metrics["split"] == "later"].copy()
    alert = observed["alert"]

    st.subheader("Monitoring status")
    status_color = {"OK": "🟢", "WARNING": "🟠", "RETRAIN_REVIEW": "🔴"}.get(
        alert["status"], "⚪"
    )
    left, middle, right = st.columns(3)
    left.metric("Drift alert", f"{status_color} {alert['status']}")
    middle.metric("Supervised score PSI", f"{observed['supervised_score_psi']:.3f}")
    drop = alert.get("relative_pr_auc_drop")
    right.metric("Validation → later PR-AUC change", "—" if drop is None else f"{-drop:.1%}")
    for reason in alert["reasons"]:
        st.warning(reason)
    if not alert["reasons"]:
        st.success("No configured drift or performance alert bounds were crossed.")

    st.subheader("Model comparison")
    display_columns = [
        "model", "split", "pr_auc", "roc_auc", "threshold", "precision", "recall",
        "false_positive_count", "false_negative_count", "false_positive_cost",
        "false_negative_cost", "total_cost",
    ]
    st.dataframe(
        metrics[display_columns].sort_values(["split", "pr_auc"], ascending=[True, False]),
        use_container_width=True,
        hide_index=True,
        column_config={
            "pr_auc": st.column_config.NumberColumn("PR-AUC (primary)", format="%.4f"),
            "roc_auc": st.column_config.NumberColumn("ROC-AUC", format="%.4f"),
            "threshold": st.column_config.NumberColumn("Validation threshold", format="%.5f"),
            "total_cost": st.column_config.NumberColumn("Estimated cost", format="$%.2f"),
            "false_positive_cost": st.column_config.NumberColumn("False-positive cost", format="$%.2f"),
            "false_negative_cost": st.column_config.NumberColumn("False-negative cost", format="$%.2f"),
        },
    )

    metric_choice = st.selectbox("Chart metric", ["pr_auc", "total_cost", "precision", "recall"], index=0)
    chart_data = metrics.pivot(index="model", columns="split", values=metric_choice)
    st.bar_chart(chart_data, use_container_width=True)

    left, right = st.columns(2)
    with left:
        st.markdown("#### Feature drift (PSI)")
        psi_frame = pd.DataFrame(
            [{"feature": name, "PSI": value} for name, value in observed["feature_psi"].items()]
        ).sort_values("PSI", ascending=False)
        st.dataframe(psi_frame, use_container_width=True, hide_index=True)
    with right:
        st.markdown("#### Validation precision-recall curves")
        image_path = RESULTS_DIR / "validation_pr_curves.png"
        if image_path.exists():
            st.image(str(image_path), use_container_width=True)
        else:
            st.caption("No curve image was generated by the last run.")

    with st.expander("Synthetic drift demonstration"):
        synthetic = drift["synthetic_demo"]
        st.caption(synthetic["label"])
        st.metric("Synthetic maximum feature PSI", f"{synthetic['max_feature_psi']:.3f}")
        synthetic_frame = pd.DataFrame(
            [{"feature": name, "PSI": value} for name, value in synthetic["feature_psi"].items()]
        ).sort_values("PSI", ascending=False)
        st.dataframe(synthetic_frame, use_container_width=True, hide_index=True)

    st.download_button(
        "Download metrics CSV",
        metrics.to_csv(index=False).encode("utf-8"),
        file_name="fraud_metrics.csv",
        mime="text/csv",
    )
    st.download_button(
        "Download drift report JSON",
        json.dumps(drift, indent=2).encode("utf-8"),
        file_name="drift_report.json",
        mime="application/json",
    )


st.title("🛡️ Fraud & Drift Monitor")
st.markdown(
    "Compare a class-weighted fraud classifier with an unsupervised anomaly detector, "
    "then inspect performance and drift on a later transaction window."
)

with st.container(border=True):
    st.subheader("Run an experiment")
    st.caption("Chronological split: 60% train · 20% validation · 20% later")
    uploaded_file = st.file_uploader("Upload creditcard.csv", type=["csv"])
    if not uploaded_file:
        st.caption(f"Using the default dataset when available: `{DATA_PATH}`")
    run_button = st.button("Run experiment", type="primary", use_container_width=True)

if run_button:
    temporary_path = None
    try:
        if uploaded_file:
            with tempfile.NamedTemporaryFile(mode="wb", suffix=".csv", delete=False) as temp_file:
                temp_file.write(uploaded_file.getvalue())
                temporary_path = Path(temp_file.name)
            data_path = temporary_path
        else:
            data_path = DATA_PATH

        if not data_path.is_file():
            st.error("Dataset not found. Upload the Kaggle CSV or place it at data/creditcard.csv.")
        else:
            progress = st.status("Running training and evaluation…", expanded=True)
            process = subprocess.run(
                [sys.executable, str(PROJECT_ROOT / "run_all.py"), "--data", str(data_path)],
                cwd=PROJECT_ROOT,
                capture_output=True,
                text=True,
                check=False,
            )
            if process.returncode:
                progress.update(label="Experiment failed", state="error")
                st.error("The run stopped with an error. Check the details below.")
                st.code(process.stderr or process.stdout)
            else:
                progress.update(label="Experiment complete", state="complete")
                st.success("Results are ready below.")
                if process.stdout:
                    with st.expander("Run log"):
                        st.code(process.stdout)
                show_results()
    except Exception as error:
        st.exception(error)
    finally:
        if temporary_path and temporary_path.exists():
            temporary_path.unlink()
else:
    show_results()

st.divider()
st.caption(
    "Thresholds are selected on validation data and frozen for later evaluation. "
    "Costs and PSI bounds are illustrative; review README.md before interpreting results."
)
